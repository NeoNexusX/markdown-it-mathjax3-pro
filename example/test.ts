/**
 * Server-side rendering example.
 *
 * In your own project this import would read:
 *     import MarkdownItMathJaX3PRO from 'markdown-it-mathjax3-pro';
 * The relative path is only used so the example runs against this repository.
 */
import MarkdownIt from 'markdown-it';
import { writeFileSync } from 'fs';
import { join } from 'path';
import MarkdownItMathJaX3PRO = require('../index');
import { sampleMarkdown } from './sample';

const md = MarkdownIt().use(MarkdownItMathJaX3PRO, {
    tex: { tags: 'ams' },
    chtml: {
        fontURL: 'https://cdn.jsdelivr.net/npm/mathjax@3/es5/output/chtml/fonts/woff-v2',
    },
});

// The stylesheet MathJax produces for the page is written to `env`, so the same
// env object has to be passed to render and read afterwards.
const env: Record<string, any> = {};
const result = md.render(sampleMarkdown, env);
const stylesheet: string = env.mathjax_stylesheet || '';

const htmlContent = `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Direction Cosines - Server-Side Rendering</title>
    <style>
        body {
            font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
            max-width: 800px;
            margin: 0 auto;
            padding: 20px;
            line-height: 1.6;
        }
        /* Generated by MathJax; required for correct layout and for hiding
           the assistive MathML from sighted readers. */
${stylesheet}
    </style>
</head>
<body>
${result}
</body>
</html>`;

const outputPath = join(__dirname, '..', '..', 'test.html');
writeFileSync(outputPath, htmlContent, 'utf8');

console.log(`HTML file generated successfully: ${outputPath}`);
